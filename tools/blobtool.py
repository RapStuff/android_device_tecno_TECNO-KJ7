"""Extract the KJ7 stock inventory and generate LineageOS 21 prebuilt rules."""
import argparse
from collections import defaultdict
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import shutil
import sys

DEVICE = Path(__file__).resolve().parent.parent
TOP = DEVICE.parents[2]
VENDOR = TOP / 'vendor/tecno/TECNO-KJ7'
BLOBS = VENDOR / 'proprietary'
VENDOR_REL = 'vendor/tecno/TECNO-KJ7'
DEVICE_REL = 'device/tecno/TECNO_KJ7'
HEADER = '# Generated by device/tecno/TECNO_KJ7/setup-makefiles.sh.\n'


def inventory():
    entries = []
    for line in (DEVICE / 'proprietary-files.txt').read_text().splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        p = PurePosixPath(line)
        if p.is_absolute() or '..' in p.parts or not re.fullmatch(r'[\w./@+\[\]-]+', line):
            raise ValueError(f'invalid proprietary path: {line}')
        entries.append(line)
    if len(set(entries)) != len(entries):
        raise ValueError('duplicate proprietary paths')
    return entries


def extract(source, entries):
    missing = [p for p in entries if not (source / p).is_symlink() and not (source / p).is_file()]
    if missing:
        raise ValueError('missing proprietary files:\n' + '\n'.join(missing))
    for p in entries:
        src, dst = source / p, BLOBS / p
        dst.parent.mkdir(parents=True, exist_ok=True)
        if dst.is_symlink():
            dst.unlink()
        if src.is_symlink():
            dst.unlink(missing_ok=True)
            dst.symlink_to(src.readlink())
        else:
            shutil.copy2(src, dst, follow_symlinks=False)
    print(f'Extracted {len(entries)} entries to {BLOBS}')


def module_name(kind, key):
    slug = re.sub(r'[^A-Za-z0-9_]', '_', key)
    digest = hashlib.sha256(key.encode()).hexdigest()[:10]
    return f'kj7_{kind}_{slug}_{digest}'


def elf_class(path):
    with path.open('rb') as f:
        header = f.read(20)
    if header[:4] != b'\x7fELF' or header[5] != 1 or header[16:18] != b'\x03\x00':
        return None
    return {1: 'arm', 2: 'arm64'}.get(header[4])


def emit(vdir, name, text):
    path = vdir / name
    path.write_text(text, encoding='utf-8')


def make_list(name, values):
    if not values:
        return ''
    separator = ' ' + chr(92) + '\n    '
    return f'{name} +={separator}' + separator.join(values) + '\n'


def generate(entries, output):
    output.mkdir(parents=True, exist_ok=True)
    libs = defaultdict(dict)
    copy = []
    symlinks = []
    stock_only = ('vendor/etc/selinux/', 'vendor/overlay/', 'vendor/app/',
                  'vendor/etc/vintf/', 'vendor/odm/etc/vintf/', 'vendor/lib/modules')
    for p in entries:
        src = BLOBS / p
        if not src.is_symlink() and not src.is_file():
            raise ValueError(f'extract before generating makefiles: {src}')
        if not p.startswith('vendor/'):
            continue
        if p.startswith(stock_only) or p in {
                'vendor/build.prop', 'vendor/etc/fs_config_files', 'vendor/etc/fs_config_dirs',
                'vendor/etc/fstab.mt6789'}:
            continue
        if src.is_symlink():
            symlinks.append((p.removeprefix('vendor/'), str(src.readlink())))
            continue
        _, directory, *parts = PurePosixPath(p).parts
        if directory in ('lib', 'lib64') and p.endswith('.so'):
            arch = elf_class(src)
            if arch == ('arm' if directory == 'lib' else 'arm64'):
                libs['/'.join(parts)][arch] = f'proprietary/{p}'
                continue
        copy.append(f'{VENDOR_REL}/proprietary/{p}:$(TARGET_COPY_OUT_VENDOR)/{p[7:]}')

    bp = '// Generated by device/tecno/TECNO_KJ7/setup-makefiles.sh.\n\nsoong_namespace {}\n'
    packages = []
    for relative, archs in sorted(libs.items()):
        stem = PurePosixPath(relative).stem
        name = module_name('lib', relative)
        packages.append(name)
        multilib = {'arm': '32', 'arm64': '64'}[next(iter(archs))] if len(archs) == 1 else 'both'
        bp += '\ncc_prebuilt_library_shared {\n'
        bp += f'    name: {json.dumps(name)},\n    stem: {json.dumps(stem)},\n'
        bp += '    proprietary: true,\n    check_elf_files: false,\n'
        bp += '    strip: {\n        none: true,\n    },\n    stl: "none",\n    system_shared_libs: [],\n'
        bp += f'    compile_multilib: "{multilib}",\n'
        directory = PurePosixPath(relative).parent
        if directory != PurePosixPath('.'):
            bp += f'    relative_install_path: {json.dumps(str(directory))},\n'
        bp += '    arch: {\n'
        for arch, src in sorted(archs.items()):
            bp += f'        {arch}: {{\n            srcs: [{json.dumps(src)}],\n        }},\n'
        bp += '    },\n}\n'
    emit(output, 'Android.bp', bp)

    copy_vintf = [
        f'{DEVICE_REL}/vintf/fragments/{f.name}:$(TARGET_COPY_OUT_VENDOR)/etc/vintf/manifest/{f.name}'
        for f in sorted((DEVICE / 'vintf/fragments').glob('*.xml'))
    ]
    odm = DEVICE / 'vintf/odm'
    for f in sorted(odm.rglob('*.xml')):
        rel = f.relative_to(odm).as_posix()
        copy_vintf.append(f'{DEVICE_REL}/vintf/odm/{rel}:$(TARGET_COPY_OUT_VENDOR)/odm/etc/vintf/{rel}')
    make = HEADER + 'ifneq ($(TARGET_PRODUCT),aosp_TECNO_KJ7)\n'
    make += 'ifneq ($(wildcard hardware/interfaces/compatibility_matrices/compatibility_matrix.6.xml),)\n'
    make += make_list('PRODUCT_COPY_FILES', copy_vintf)
    make += 'endif\n'
    make += 'endif\n'
    make += '\nifeq ($(KJ7_REBUILD_VENDOR),true)\n'
    make += f'PRODUCT_SOONG_NAMESPACES += {VENDOR_REL}\n'
    make += f'PRODUCT_COPY_FILES += {DEVICE_REL}/rootdir/etc/fstab.mt6789:$(TARGET_COPY_OUT_VENDOR)/etc/fstab.mt6789\n'
    make += make_list('PRODUCT_PACKAGES', packages)
    make += make_list('PRODUCT_COPY_FILES', copy)
    make += 'endif\n'
    emit(output, 'TECNO-KJ7-vendor.mk', make)
    emit(output, 'BoardConfigVendor.mk', HEADER + f'''
# Default: stock vendor keeps OEM policy, file labels and HAL binary metadata.
ifneq ($(KJ7_REBUILD_VENDOR),true)
BOARD_PREBUILT_VENDORIMAGE := {VENDOR_REL}/prebuilt-images/vendor.img
else
# Development only: binaries and configs are staged while the vendor policy is ported.
BUILD_BROKEN_ELF_PREBUILT_PRODUCT_COPY_FILES := true
endif
''')
    # The stock image already owns these links. Register them only for source vendor.
    mk = HEADER + 'ifneq ($(filter TECNO-KJ7 TECNO_KJ7,$(TARGET_DEVICE)),)\nifeq ($(KJ7_REBUILD_VENDOR),true)\n'
    for relative, target in symlinks:
        if not re.fullmatch(r'[\w./@+\[\]-]+', target):
            raise ValueError(f'unrepresentable symlink target: {relative} -> {target}')
        dst = '$(TARGET_OUT_VENDOR)/' + relative
        mk += (f'{dst}:\n\t@mkdir -p "$(@D)"\n\t@ln -sfn -- "{target}" "$@"\n'
               f'ALL_DEFAULT_INSTALLED_MODULES += {dst}\n')
    mk += 'endif\nendif\n'
    emit(output, 'Android.mk', mk)
    print(f'Generated {len(packages)} shared library modules, {len(copy)} copies and {len(symlinks)} symlinks.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, help='extracted Android dump')
    parser.add_argument('--output', type=Path, default=VENDOR, help=argparse.SUPPRESS)
    args = parser.parse_args()
    try:
        entries = inventory()
        if args.source:
            extract(args.source.resolve(), entries)
        generate(entries, args.output)
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
